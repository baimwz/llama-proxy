#!/usr/bin/env bash
# setup-llm-gateway.sh -- turn the Pi into a NAT gateway for the LLM host.
#
# Topology:
#   home LAN  <==  Pi (this box)  <==  LLM host (Proxmox, one NIC)
#                eth0 (DHCP)          USB GbE, 10.42.0.1/24
#
# The LLM host gets its internet through the Pi (masquerade/NAT). It stays
# invisible to the rest of the LAN (forward policy is drop).
#
# Usage (run on the Pi, as root):
#   sudo scripts/setup-llm-gateway.sh show               # what will happen
#   sudo scripts/setup-llm-gateway.sh apply              # do it
#   sudo scripts/setup-llm-gateway.sh test               # verify uplink
#   sudo scripts/setup-llm-gateway.sh proxmox-config     # print host-side config
#   sudo scripts/setup-llm-gateway.sh uninstall          # revert
#
# Options:
#   --lan-if NAME     home-LAN interface (default: auto, non-USB)
#   --llm-if  NAME    LLM-host interface   (default: auto, USB)
#   --llm-addr IP     gateway IP for the LLM host (default: 10.42.0.1)
#   --llm-cidr N      prefix length        (default: 24)
#   --dns IP[,IP]     DNS for the LLM host (default: 1.1.1.1,9.9.9.9)
#   --dry-run         print actions, change nothing
#
# Idempotent: safe to re-run. Every file that is modified is backed up to
# /var/backups/llama-gateway/ first.

set -euo pipefail

# ---------------------------------------------------------------------------
# defaults / globals
# ---------------------------------------------------------------------------
LAN_IF=""
LLM_IF=""
LLM_ADDR="10.42.0.1"
LLM_CIDR="24"
DNS="1.1.1.1,9.9.9.9"
DRY_RUN=0
CMD="show"

BACKUP_DIR="/var/backups/llama-gateway"
NM_CON="llama-llm"
NETWORKD_FILE="/etc/systemd/network/25-llama-gateway.network"
IFUPDOWN_FILE="/etc/network/interfaces"
SYSCTL_FILE="/etc/sysctl.d/90-llama-gateway.conf"
NFT_FILE="/etc/nftables.conf"

# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
log()  { printf '  \033[32m==>\033[0m %s\n' "$*"; }
warn() { printf '  \033[33mwarn:\033[0m %s\n' "$*" >&2; }
die()  { printf '  \033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

usage() { sed -n '2,27p' "$0" | sed 's/^# \{0,1\}//'; }

backup() {  # backup FILE
    local f="$1"
    [ -f "$f" ] || return 0
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '  \033[36mdry-run:\033[0m would back up %s\n' "$f"
        return 0
    fi
    mkdir -p "$BACKUP_DIR"
    local ts; ts="$(date +%Y%m%d-%H%M%S)"
    cp -a "$f" "$BACKUP_DIR/$(basename "$f").$ts"
    log "backed up $f -> $BACKUP_DIR/"
}

run() {  # run CMD...  (honours --dry-run)
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '  \033[36mdry-run:\033[0m %s\n' "$*"
    else
        "$@"
    fi
}

write_file() {  # write_file PATH  (content on stdin; honours --dry-run)
    if [ "$DRY_RUN" -eq 1 ]; then
        local content; content="$(cat)"
        printf '  \033[36mdry-run:\033[0m write %s\n' "$1"
        printf '%s\n' "$content" | sed 's/^/    | /'
    else
        cat > "$1"
    fi
}

# ---------------------------------------------------------------------------
# detection
# ---------------------------------------------------------------------------
is_usb_if() {
    local ifc="$1" dev
    dev="$(readlink -f "/sys/class/net/$ifc/device" 2>/dev/null || true)"
    [[ "$dev" == *usb* ]]
}

detect_interfaces() {
    [ -n "$LAN_IF" ]  || LAN_IF="$(for i in /sys/class/net/*; do
        i="$(basename "$i")"; [ "$i" = lo ] && continue
        is_usb_if "$i" || { echo "$i"; break; }
    done)"
    [ -n "$LLM_IF" ]  || LLM_IF="$(for i in /sys/class/net/*; do
        i="$(basename "$i")"; [ "$i" = lo ] && continue
        is_usb_if "$i" && { echo "$i"; break; }
    done)"
    [ -n "$LAN_IF" ] || die "could not detect a non-USB interface (use --lan-if)"
    [ -n "$LLM_IF" ] || die "could not detect a USB interface (use --llm-if)"
}

detect_netstack() {
    if command -v nmcli >/dev/null 2>&1 \
        && nmcli -o -f STATE device 2>/dev/null | grep -q connected; then
        echo networkmanager
    elif systemctl is-active --quiet systemd-networkd 2>/dev/null; then
        echo networkd
    elif [ -f "$IFUPDOWN_FILE" ]; then
        echo ifupdown
    else
        echo unknown
    fi
}

lan_gateway() {
    ip -4 route show default | awk '/default/ {print $3; exit}'
}

# ---------------------------------------------------------------------------
# configuration
# ---------------------------------------------------------------------------
write_networkd() {
    backup "$NETWORKD_FILE"
    write_file "$NETWORKD_FILE" <<EOF
# generated by setup-llm-gateway.sh
[Match]
Name=$LLM_IF
[Network]
Address=$LLM_ADDR/$LLM_CIDR
EOF
    run systemctl enable --now systemd-networkd
    run networkctl reconfigure "$LLM_IF"
}

write_networkmanager() {
    local existing
    existing="$(nmcli -t -f NAME con show 2>/dev/null | grep -x "$NM_CON" || true)"
    if [ -n "$existing" ]; then
        run nmcli con modify "$NM_CON" ifname "$LLM_IF" \
            ipv4.method manual ipv4.addresses "$LLM_ADDR/$LLM_CIDR" \
            ipv6.method ignore
    else
        run nmcli con add type ethernet ifname "$LLM_IF" con-name "$NM_CON" \
            ipv4.method manual ipv4.addresses "$LLM_ADDR/$LLM_CIDR" \
            ipv6.method ignore connection.autoconnect yes
    fi
    run nmcli con up "$NM_CON" 2>/dev/null || warn "connection not activated yet (cable plugged in?)"
}

write_ifupdown() {
    backup "$IFUPDOWN_FILE"
    # remove a stanza we previously wrote (if any), then append a fresh one
    local base=""
    if [ -f "$IFUPDOWN_FILE" ]; then
        base="$(awk -v ifc="$LLM_IF" '
            $1 == "auto" && $2 == ifc { skip = 1; next }
            $1 == "iface" && $2 == ifc { skip = 1; next }
            skip && /^$/ { next }
            skip { if ($0 !~ /^[[:space:]]/) skip = 0; else next }
            { print }
        ' "$IFUPDOWN_FILE")"
    fi
    {
        if [ -n "$base" ]; then printf '%s\n' "$base"; fi
        cat <<EOF

# generated by setup-llm-gateway.sh
auto $LLM_IF
iface $LLM_IF inet static
    address $LLM_ADDR/$LLM_CIDR
EOF
    } | write_file "$IFUPDOWN_FILE"
    run ifup "$LLM_IF" 2>/dev/null || warn "interface not up yet (cable plugged in?)"
}

write_nftables() {
    command -v nft >/dev/null 2>&1 || {
        log "nftables not found, installing..."
        run apt-get update -qq
        run apt-get install -y -qq nftables
    }
    backup "$NFT_FILE"
    write_file "$NFT_FILE" <<EOF
#!/usr/sbin/nft -f
# generated by setup-llm-gateway.sh
table ip filter {
    chain forward {
        type filter hook forward priority filter; policy drop;
        ct state established,related accept
        iifname "$LLM_IF" oifname "$LAN_IF" ip saddr $(cidr_to_net "$LLM_CIDR")/$LLM_CIDR ct state new accept
    }
}
table ip nat {
    chain postrouting {
        type nat hook postrouting priority 100;
        oifname "$LAN_IF" ip saddr $(cidr_to_net "$LLM_CIDR")/$LLM_CIDR masquerade
    }
}
EOF
    run nft -f "$NFT_FILE"
    run systemctl enable nftables
}

cidr_to_net() {  # cidr_to_net 24 -> 10.42.0.0
    local cidr="$1"
    if command -v ipcalc >/dev/null 2>&1; then
        ipcalc -c "$LLM_ADDR/$cidr" | awk -F= '/^Network/ {gsub(/ /,"",$2); print $2}'
    else
        # portable fallback (works for /8..30 on a single IPv4)
        local -a oct; IFS=. read -r -a oct <<< "$LLM_ADDR"
        local net=$(( (oct[0] << 24 | oct[1] << 16 | oct[2] << 8 | oct[3]) & \
                      (0xFFFFFFFF << (32 - cidr) & 0xFFFFFFFF) ))
        echo "$(( (net >> 24) & 255 )).$(( (net >> 16) & 255 )).$(( (net >> 8) & 255 )).$(( net & 255 ))"
    fi
}

write_sysctl() {
    backup "$SYSCTL_FILE"
    printf 'net.ipv4.ip_forward = 1\n' | write_file "$SYSCTL_FILE"
    run sysctl -w net.ipv4.ip_forward=1
}

# ---------------------------------------------------------------------------
# commands
# ---------------------------------------------------------------------------
cmd_show() {
    detect_interfaces
    local netstack gw
    netstack="$(detect_netstack)"
    gw="$(lan_gateway || true)"
    echo "pi-gateway configuration"
    echo "  command          : $CMD"
    echo "  LAN interface    : $LAN_IF (gateway: ${gw:-n/a})"
    echo "  LLM interface    : $LLM_IF (USB: $(is_usb_if "$LLM_IF" && echo yes || echo no))"
    echo "  LLM gateway IP   : $LLM_ADDR/$LLM_CIDR"
    echo "  LLM host IP      : $(bump_oct "$LLM_ADDR" 1)/$LLM_CIDR  (suggested)"
    echo "  DNS for host     : $DNS"
    echo "  network manager  : $netstack"
    echo "  ip_forward       : $(sysctl -n net.ipv4.ip_forward 2>/dev/null || echo 0)"
    echo "  nftables         : $(nft list ruleset 2>/dev/null | grep -c masquerade || true) masquerade rule(s)"
    echo
    echo "the LLM host (Proxmox) will need, in /etc/network/interfaces:"
    cmd_proxmox_config | sed 's/^/  /'
}

bump_oct() {  # bump the last octet of an address by $2
    local -a o; IFS=. read -r -a o <<< "$1"
    local last=$(( o[3] + $2 ))
    echo "${o[0]}.${o[1]}.${o[2]}.${last}"
}

cmd_apply() {
    if [ "$DRY_RUN" -eq 0 ]; then
        [ "$(id -u)" -eq 0 ] || die "run as root (sudo scripts/setup-llm-gateway.sh apply)"
    fi
    detect_interfaces
    local netstack
    netstack="$(detect_netstack)"
    [ "$netstack" != "unknown" ] || die "no supported network manager found (expected NetworkManager, systemd-networkd or ifupdown)"

    ip link show "$LLM_IF" >/dev/null 2>&1 || die "interface $LLM_IF does not exist"

    echo "applying pi-gateway configuration"
    case "$netstack" in
        networkd)        log "configuring $LLM_IF via systemd-networkd"; write_networkd ;;
        networkmanager)  log "configuring $LLM_IF via NetworkManager";  write_networkmanager ;;
        ifupdown)        log "configuring $LLM_IF via ifupdown";        write_ifupdown ;;
    esac
    write_sysctl
    write_nftables

    sleep 1
    if ip -4 addr show "$LLM_IF" | grep -q "$LLM_ADDR"; then
        log "$LLM_IF is up with $LLM_ADDR/$LLM_CIDR"
    else
        warn "$LLM_IF does not show $LLM_ADDR yet (cable plugged in? adapter recognised?)"
    fi
    echo
    echo "done. Next steps:"
    echo "  1. plug the cable into the LLM host"
    echo "  2. on the LLM host: $(cmd_proxmox_hint)"
    echo "  3. test:  sudo $0 test"
    echo
    cmd_proxmox_config | sed 's/^/  /'
}

cmd_proxmox_hint() {
    echo "set the stanza below in /etc/network/interfaces, then 'systemctl restart networking'"
}

cmd_proxmox_config() {
    local host_ip; host_ip="$(bump_oct "$LLM_ADDR" 1)"
    cat <<EOF
# /etc/network/interfaces on the LLM host (adjust NIC name, e.g. enp1s0)
auto enp1s0
iface enp1s0 inet static
    address $host_ip/$LLM_CIDR
    gateway $LLM_ADDR
    dns-nameservers ${DNS//,/ }

# then:
#   systemctl restart networking
#   ping -c3 $LLM_ADDR
#   ping -c3 1.1.1.1
#   curl -sI https://huggingface.co | head -2
#   apt-get update
EOF
}

cmd_test() {
    detect_interfaces
    local gw; gw="$(lan_gateway || true)"
    echo "testing uplink from the Pi"
    if [ -n "$gw" ]; then
        if ping -c1 -W2 "$gw" >/dev/null 2>&1; then log "LAN gateway $gw reachable"; else warn "LAN gateway $gw NOT reachable"; fi
    else
        warn "no default route on the Pi - is the home LAN up?"
    fi
    if curl -sI -m 5 https://huggingface.co >/dev/null 2>&1; then
        log "internet via the Pi OK (huggingface.co)"
    else
        warn "internet via the Pi NOT reachable"
    fi
    if ip -4 addr show "$LLM_IF" 2>/dev/null | grep -q "$LLM_ADDR"; then
        log "$LLM_IF has $LLM_ADDR"
    else
        warn "$LLM_IF has no address (cable/adapter?)"
    fi
    if [ "$(sysctl -n net.ipv4.ip_forward 2>/dev/null)" = "1" ]; then
        log "ip_forward enabled"
    else
        warn "ip_forward disabled (run: apply)"
    fi
    if nft list ruleset 2>/dev/null | grep -q masquerade; then
        log "nftables masquerade present"
    else
        warn "no masquerade rule (run: apply)"
    fi
    echo
    echo "LLM-host side (run over there):"
    echo "  ping -c3 $LLM_ADDR && ping -c3 1.1.1.1 && curl -sI https://huggingface.co | head -2"
}

cmd_uninstall() {
    if [ "$DRY_RUN" -eq 0 ]; then
        [ "$(id -u)" -eq 0 ] || die "run as root"
    fi
    detect_interfaces
    local netstack; netstack="$(detect_netstack)"
    case "$netstack" in
        networkd)
            backup "$NETWORKD_FILE"
            run rm -f "$NETWORKD_FILE"
            run networkctl reconfigure "$LLM_IF" || true
            ;;
        networkmanager)
            run nmcli con delete "$NM_CON" 2>/dev/null || true
            ;;
        ifupdown)
            backup "$IFUPDOWN_FILE"
            if [ -f "$IFUPDOWN_FILE" ]; then
                local tmp; tmp="$(mktemp)"
                awk -v ifc="$LLM_IF" '
                    $1 == "auto" && $2 == ifc { skip = 1; next }
                    $1 == "iface" && $2 == ifc { skip = 1; next }
                    skip && /^$/ { next }
                    skip { if ($0 !~ /^[[:space:]]/) skip = 0; else next }
                    { print }
                ' "$IFUPDOWN_FILE" > "$tmp"
                cat "$tmp" > "$IFUPDOWN_FILE"
                rm -f "$tmp"
            fi
            run ifdown "$LLM_IF" 2>/dev/null || true
            ;;
    esac
    backup "$SYSCTL_FILE";  run rm -f "$SYSCTL_FILE"
    run sysctl -w net.ipv4.ip_forward=0
    backup "$NFT_FILE"
    if [ -f "$NFT_FILE" ] && grep -q "setup-llm-gateway" "$NFT_FILE"; then
        run nft flush ruleset
        run rm -f "$NFT_FILE"
    fi
    echo "uninstall done (backups in $BACKUP_DIR)"
}

# ---------------------------------------------------------------------------
# arg parsing
# ---------------------------------------------------------------------------
while [ $# -gt 0 ]; do
    case "$1" in
        show|apply|test|uninstall|proxmox-config) CMD="$1" ;;
        --lan-if)   LAN_IF="$2";  shift ;;
        --llm-if)   LLM_IF="$2";  shift ;;
        --llm-addr) LLM_ADDR="$2"; shift ;;
        --llm-cidr) LLM_CIDR="$2"; shift ;;
        --dns)      DNS="$2";     shift ;;
        --dry-run)  DRY_RUN=1 ;;
        -h|--help)  usage; exit 0 ;;
        *) die "unknown argument: $1 (see --help)" ;;
    esac
    shift
done

case "$CMD" in
    show)           cmd_show ;;
    apply)          cmd_apply ;;
    test)           cmd_test ;;
    proxmox-config) cmd_proxmox_config ;;
    uninstall)      cmd_uninstall ;;
esac
